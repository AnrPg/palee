  @doc "The entry for a controller action: a key, `{:by_param, ...}`, `:skip` or nil."
  def for_action(controller, action), do: Map.get(@routes, {controller, action})

  @doc "The key a request records, or nil (skipped, unknown, or a parameter with no key)."
  def key(controller, action, path_params) do
    case for_action(controller, action) do
      key when is_binary(key) -> key
      {:by_param, name, keys} -> Map.get(keys, path_params[name])
      _skip_or_unknown -> nil
    end
  end

  @doc "Every key the routes can record."
  def keys do
    @routes
    |> Map.values()
    |> Enum.flat_map(fn
      key when is_binary(key) -> [key]
      {:by_param, _name, keys} -> Map.values(keys)
      :skip -> []
    end)
    |> Enum.uniq()
  end
