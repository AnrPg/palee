  def areas, do: @areas
  def keys, do: @actions |> Map.keys() |> Enum.sort()
  def known?(key), do: is_map_key(@actions, key)

  @doc "The area a key belongs to."
  def area(key) do
    case Map.fetch(@actions, key) do
      {:ok, {area, :sensitive}} -> area
      {:ok, area} when is_atom(area) -> area
      :error -> nil
    end
  end

  @doc "Whether the owner's daily summary lists the key (ANR 12B)."
  def sensitive?(key), do: match?({:ok, {_area, :sensitive}}, Map.fetch(@actions, key))

  def sensitive_keys, do: Enum.filter(keys(), &sensitive?/1)
end
